import '../domain/note_outline.dart';
import '../domain/study_note.dart';

/// DEVELOPMENT FIXTURE — used only under `flutter test` or
/// `--dart-define=USE_MOCK_BACKEND=true`, to build the outline UI while the
/// Gemini quota is unavailable.
///
/// Rules: lives in memory only (never sent to the server or MongoDB), every
/// outline and section is flagged [NoteOutline.isSample] / `isSample` and
/// shown with a "Development sample" label, and the text is placeholder
/// wording — not study material, not AI-generated, not verified.
class SampleOutlineRepository implements OutlineRepository {
  SampleOutlineRepository({this.latency = const Duration(milliseconds: 300)});

  final Duration latency;

  /// Fails the next [openSection] like an exhausted Gemini quota (tests).
  Object? failNext;

  static const sampleModel = 'dev-fixture';

  static const _chapters = [
    (
      'ch1',
      'Sample chapter 1: Introduction',
      'high',
      [
        ('s1', 'Sample section 1.1: Overview'),
        ('s2', 'Sample section 1.2: Key terms'),
      ],
    ),
    (
      'ch2',
      'Sample chapter 2: Core ideas',
      'medium',
      [
        ('s1', 'Sample section 2.1: First idea'),
        ('s2', 'Sample section 2.2: Second idea'),
        ('s3', 'Sample section 2.3: Practice'),
      ],
    ),
  ];

  final Map<String, SectionState> _states = {};

  String _id(OutlineKey k, SectionRef s) =>
      '${k.examId}|${k.unitId}|${s.chapterId}.${s.sectionId}';

  @override
  Future<NoteOutline> outline(OutlineKey k) async {
    await Future<void>.delayed(latency);
    return _build(k);
  }

  NoteOutline _build(OutlineKey k) {
    SectionRef? next;
    final chapters = [
      for (final (cid, title, weight, sections) in _chapters)
        OutlineChapter(
          id: cid,
          title: title,
          weight: weight,
          sections: [
            for (final (sid, stitle) in sections)
              () {
                final state =
                    _states[_id(k, (chapterId: cid, sectionId: sid))] ??
                    SectionState.pending;
                if (next == null && state != SectionState.completed) {
                  next = (chapterId: cid, sectionId: sid);
                }
                return OutlineSection(id: sid, title: stitle, state: state);
              }(),
          ],
        ),
    ];
    return NoteOutline(
      examId: k.examId,
      unitId: k.unitId,
      title: 'Sample outline (development)',
      status: 'draft',
      version: 1,
      language: k.language,
      mode: k.mode,
      chapters: chapters,
      continueAt: next,
      isSample: true,
    );
  }

  @override
  Future<OpenedSection> openSection(OutlineKey k, SectionRef s) async {
    await Future<void>.delayed(latency);
    if (failNext case final e?) {
      failNext = null;
      _states[_id(k, s)] = SectionState.failed;
      throw e;
    }
    final title = _build(k).ordered
        .firstWhere((e) => e.$1.id == s.chapterId && e.$2.id == s.sectionId)
        .$2
        .title;
    final id = _id(k, s);
    if (_states[id] != SectionState.completed) {
      _states[id] = SectionState.generated;
    }
    return (
      note: StudyNote(
        id: 'sample:$id',
        category: 'sample',
        examId: k.examId,
        examName: 'Sample exam',
        subjectId: 'sample',
        subjectName: 'Development sample',
        topicId: k.unitId,
        topicName: title,
        language: k.language,
        level: NoteLevel.examStandard,
        createdAt: DateTime.now(),
        model: sampleModel,
        content: NoteContent(
          overview:
              'Placeholder text for UI development. This is not study '
              'material and was not generated by AI.',
          explanation: const [
            NoteParagraph(
              'Sample heading',
              'Lorem ipsum placeholder paragraph used to check layout, '
                  'scrolling and section navigation.',
            ),
          ],
          keyPoints: const ['Sample key point one', 'Sample key point two'],
        ),
      ),
      source: 'sample',
      isSample: true,
      contentStatus: null,
      review: null,
      verification: null,
      coverageBasis: null,
    );
  }

  /// Practice-based revision needs real results: the sample has none.
  @override
  Future<LearningRecommendations> recommendations({
    required String examId,
    required String subjectId,
    required String language,
  }) async => const LearningRecommendations();

  /// Sample tree: the subject's topics from the mock syllabus; the FIRST
  /// topic carries the sample chapters (same as the mock learning path).
  @override
  Future<SyllabusTree> tree({
    required String examId,
    required String subjectId,
    required String language,
    LearningMode mode = LearningMode.complete,
  }) async {
    await Future<void>.delayed(latency);
    final syllabus = await MockSyllabusRepository().fetchSyllabus(examId);
    final subject = syllabus.subjects
        .where((s) => s.id == subjectId)
        .firstOrNull;
    if (subject == null) {
      return SyllabusTree(
        subject: SyllabusTreeNode(
          id: subjectId,
          type: TreeNodeType.subject,
          name: subjectId,
        ),
      );
    }
    SyllabusTreeNode chaptersFor(String unitId, String name) {
      final k = (
        examId: examId,
        unitId: unitId,
        language: language,
        mode: mode,
      );
      final o = _build(k);
      final chapters = [
        for (final c in o.chapters)
          SyllabusTreeNode(
            id: '$unitId#${c.id}',
            type: TreeNodeType.chapter,
            name: c.title,
            stats: TreeStats(
              sections: c.sections.length,
              completed: c.completed,
            ),
            children: [
              for (final s in c.sections)
                SyllabusTreeNode(
                  id: '$unitId#${c.id}.${s.id}',
                  type: TreeNodeType.section,
                  name: s.title,
                  content: 'not_generated',
                  progress: s.state == SectionState.completed
                      ? 'completed'
                      : 'not_started',
                  stats: TreeStats(
                    sections: 1,
                    completed: s.state == SectionState.completed ? 1 : 0,
                  ),
                  ref: (unitId: unitId, chapterId: c.id, sectionId: s.id),
                ),
            ],
          ),
      ];
      return SyllabusTreeNode(
        id: unitId,
        type: TreeNodeType.topic,
        name: name,
        stats: TreeStats(sections: o.total, completed: o.completed),
        children: chapters,
      );
    }

    final topics = [
      for (final (i, t) in subject.topics.indexed)
        i == 0
            ? chaptersFor(t.id, t.name)
            : SyllabusTreeNode(
                id: t.id,
                type: TreeNodeType.topic,
                name: t.name,
                progress: 'not_started',
              ),
    ];
    final first = topics.first;
    final nextSection = first.children
        .expand((c) => c.children)
        .where((s) => !s.isCompleted)
        .firstOrNull;
    return SyllabusTree(
      subject: SyllabusTreeNode(
        id: subject.id,
        type: TreeNodeType.subject,
        name: subject.name,
        stats: first.stats,
        children: topics,
      ),
      next: nextSection == null
          ? null
          : (id: nextSection.id, name: nextSection.name, ref: nextSection.ref),
    );
  }

  @override
  Future<NoteOutline> setSectionCompleted(
    OutlineKey k,
    SectionRef s, {
    required bool completed,
  }) async {
    await Future<void>.delayed(latency);
    final id = _id(k, s);
    _states[id] = completed ? SectionState.completed : SectionState.generated;
    return _build(k);
  }
}
